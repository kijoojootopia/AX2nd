# 1. 화면을 알록달록 꾸며주는 도구 상자 'streamlit'을 가져와서 부르기 쉽게 'st'라고 부를게!
import streamlit as st

# 2. 주사위를 굴리듯 아무 숫자나 무작위로 뽑아주는 도구 상자 'random'을 가져올게!
import random

# 3. 컴퓨터 시계를 보고 지금 몇 년, 몇 월, 몇 시인지 알려주는 도구 상자 'datetime'을 가져올게!
from datetime import datetime

# 4. 화면 맨 위에 가장 크고 굵은 글씨로 대문짝만한 제목을 달아줘!
st.title('🎱로또 번호 자동 생성기')

# 5. 제목 바로 밑에 작고 귀여운 글씨로 이 프로그램이 무슨 일을 하는지 안내 메모를 적어줘!
st.caption('버튼을 누르면 1~45 사이의 중복 없는 번호 6개 세트를 5개 만들어집니다.')

# 6. [마법 상자 1] 겹치지 않는 로또 번호 6개를 뽑아주는 기계(lotto_one_set)를 만들자!
def lotto_one_set() -> list : 
    """ 1~45에서 중복 없이 번호 6개 뽑아 정렬된 리스트로 반환"""

    # 7. 똑같은 숫자가 들어오면 스스로 튕겨내 버리는 신기한 마법 주머니(set)를 하나 꺼내!
    number = set[int]()

    # 8. 주머니 안에 들어있는 공이 6개가 될 때까지 계속 반복해서 뽑기를 할 거야!
    while len(number) < 6 :
        # 1부터 45 사이의 숫자 중 하나를 무작위로 뽑아서 주머니에 쏙 집어넣어! (이미 있는 숫자면 알아서 무시돼)
        number.add(random.randint(1,45))

    # 9. 공 6개가 다 모이면, 보기 좋게 작은 숫자부터 차례대로 줄을 세워서(sorted) 네모 상자(list)에 담아 밖으로 내보내줘!
    return sorted(number)

# 10. 형광펜으로 줄을 쫙 그어서 윗부분과 아랫부분을 깔끔하게 나눠줘!
st.markdown('---')

# 11. [버튼 누르기 검사] 만약 사용자가 초록 클로버 모양의 "5세트 번호 생성하기" 버튼을 콕 누른다면?
if st.button("🍀5세트 번호 생성하기", key="widget_button"):

    # 12. 시계를 확인해서 "년-월-일 시:분:초" 모양의 깔끔한 글자로 사진을 찰칵 찍어둬!
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    # 13. 화면에 버튼을 누른 바로 그 시각을 진한 글씨로 예쁘게 보여줘!
    st.write(f"생성시각 : **{now_str}**")

    # 14. [마법 상자 2] 숫자를 넣으면 알록달록한 공 이모지로 변신시켜 주는 기계를 만들어!
    def get_ball_emoji(num: int) -> str:
        # 숫자가 10 이하(1~10)라면 노란 공 이모지와 함께 두 자리 번호(:02d)로 돌려줘!
        if num <= 10:
            return f"🟡 {num:02d}"
        # 숫자가 20 이하(11~20)라면 파란 공 이모지를 붙여서 돌려줘!
        elif num <= 20:
            return f"🔵 {num:02d}"
        # 숫자가 30 이하(21~30)라면 빨간 공 이모지를 붙여서 돌려줘!
        elif num <= 30:
            return f"🔴 {num:02d}"
        # 그보다 더 큰 숫자(31~45)라면 하얀(회색) 공 이모지를 붙여서 돌려줘!
        else:
            return f"⚪ {num:02d}"

    # 15. 1등부터 5등 세트까지 뽑기 위해 1번부터 5번까지 5번 동안 똑같은 일을 반복해!
    for set_index in range(1,6):
        # 16. 아까 만든 뽑기 기계(lotto_one_set)를 돌려서 숫자 6개 리스트를 가져와!
        lotto_num = lotto_one_set()

        # 17. 뽑힌 숫자 6개를 하나씩 꺼내 공 이모지로 바꾸고, 공들 사이에 띄어쓰기 두 칸("  ")을 넣어 보기 좋게 이어 붙여줘!
        formatted_balls = "  ".join([get_ball_emoji(n) for n in lotto_num])

        # 18. "1세트 : 🟡 03  🔵 15 ..." 처럼 화면에 한 줄씩 예쁘게 찍어줘!
        st.write(f"**{set_index}세트** : {formatted_balls}")

# 19. [버튼을 아직 안 눌렀을 때] 아직 버튼을 안 눌렀다면 파란색 친절한 안내 상자를 띄워둬!
else:
    st.info("위 버튼을 누르면 행운의 로또 번호 5세트가 생성됩니다.")